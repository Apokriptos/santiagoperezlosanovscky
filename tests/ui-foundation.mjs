import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {iconAsset,iconAssets,iconAliases,icon,roleIcon} from '../src/ui-icons.js';
import {pageTitle,sectionTitle,headerPlate,surface,button,carouselArrow,indexTabs,contextRail,mediaFrame} from '../src/ui.js';
import {gamesShell} from '../src/shell.js';
const index=JSON.parse(await readFile(new URL('../assets/ui/asset-index.json',import.meta.url)));
assert.equal(Object.keys(iconAssets).length,13);
for(const entry of index.entries){assert.equal(iconAssets[entry.id],entry.path);assert.ok(iconAsset(entry.id).endsWith(entry.path));}
assert.deepEqual(iconAliases,index.aliases);
assert.equal(iconAsset('previous'),iconAsset('arrow-left'));
assert.equal(iconAsset('ui_action_download.svg'),iconAsset('download'));
assert.ok(!icon('play').includes('<path'));
assert.ok(icon('play').includes('aria-hidden="true"'));
assert.throws(()=>icon('missing-icon'),RangeError);
assert.throws(()=>roleIcon('folder'),RangeError);
assert.ok(roleIcon('product-ownership').includes('ui-role-icon'));
assert.ok(pageTitle('<unsafe>').includes('&lt;unsafe&gt;'));
assert.ok(!pageTitle('Title',{slash:false}).includes('ui-page-title--slash'));
assert.throws(()=>pageTitle('Title',{level:7}),RangeError);
assert.ok(sectionTitle('Section').includes('ui-plate--red'));
assert.ok(headerPlate('Variable header').includes('ui-header-plate'));
assert.ok(surface('<p>trusted slot</p>',{accent:true}).includes('ui-surface--accent'));
assert.throws(()=>surface('x',{tag:'script'}),TypeError);
assert.ok(button('Go',{href:'#games'}).includes('href="#games"'));
const disabled=button('Unavailable',{href:'https://example.com',disabled:true});
assert.ok(disabled.includes('aria-disabled="true"') && !disabled.includes(' href='));
assert.throws(()=>button('Unsafe',{href:'javascript:alert(1)'}),TypeError);
assert.throws(()=>button('Unsafe',{attributes:{onclick:'x'}}),TypeError);
assert.throws(()=>button(''),TypeError);
assert.throws(()=>button(null),TypeError);
assert.throws(()=>carouselArrow('next'),TypeError);
assert.ok(carouselArrow('previous',{label:'Previous screenshot'}).includes('aria-label="Previous screenshot"'));
assert.ok(button('Go',{arrowHousing:true}).includes('ui-btn__arrow'));
assert.equal((indexTabs(Array.from({length:8},(_,i)=>({label:i+1,active:i===3}))).match(/aria-pressed="true"/g)||[]).length,1);
for(const kind of ['projects','roles','case-studies']){
 const rail=contextRail({kind,title:'Sample <rail>',items:[{title:'One & two',href:'#one',active:true}]});
 assert.ok(rail.includes('Sample &lt;rail&gt;') && rail.includes('One &amp; two'));
 assert.ok(rail.includes('ui-context-rail__marker') && rail.includes('aria-current="page"'));
}
assert.throws(()=>contextRail({kind:'wrong',title:'x',items:[]}),RangeError);
assert.ok(gamesShell({left:'left',main:'main'},{kind:'projects',title:'Projects',items:[]}).includes('right-rail ui-context-rail ui-project-rail'));
assert.ok(!mediaFrame('<p>Passive media</p>').includes('<button'));
assert.ok(mediaFrame('<p>media</p>',{controls:carouselArrow('next',{label:'Next image'})}).includes('ui-media-frame__controls'));
assert.throws(()=>mediaFrame('',{ratio:'1; color:red'}),TypeError);
assert.throws(()=>mediaFrame('',{ratio:'1 / 2'}),TypeError);
const pages=await readFile(new URL('../src/pages.js',import.meta.url),'utf8');
assert.ok(!pages.includes('const paths=') && !pages.includes('<path d='),'No duplicate SVG path map in pages.js');
const css=await readFile(new URL('../styles/ui-primitives.css',import.meta.url),'utf8');
assert.ok(css.includes('prefers-reduced-motion') && css.includes(':focus-visible'));
assert.ok(!/--games-(left|context)-rail-width\s*:/.test(css));
console.log('UI foundation: canonical aliases, pure renderers, safe labels/links, accessible/disabled controls, dynamic indices, separate rail kinds, passive media and reduced-motion rules passed.');
